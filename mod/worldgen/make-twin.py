#!/usr/bin/env python3
"""Write the time-travel PoC's two worlds from Klei's Spaced Out Terra, so they stay identical.

    python3 fx-sandbox/worldgen/make-twin.py [<path to expansion1 VanillaSandstoneDefault.yaml>]

The default path is under $ONI_GAME, the game install folder.

Writes fx-sandbox/worldgen/worlds/FxTimeTerra.yaml (home) and FxTimeTwinTerra.yaml (the
prehistoric twin). The two files differ ONLY in name, description, icon and starting base, because
the twin's shape must match home cell for cell (where the dinosaur is, is where the bed will be in
the future). Worldgen draws the shape from the seeds and this file, so the same
seeds (TimeTwin.SeedPatch) and the same file give the same shape. The twin turns prehistoric
AFTER the shape is drawn (TimeTwin.Convert), not through different subworlds, which would
re-roll the terrain inside every zone they replace.

Two things are taken out of BOTH copies, not only the twin, so that both still draw the same shape:
  subworldMixingRules and the (MixingN) slots: the DLC biome mixing would fill each world's slots
      from one shuffled list, so the two worlds would get different biomes.
  the Gravitas warp sender/receiver rule: a vanilla teleporter on home would target the first
      receiver on any other world, which would be the twin.
The twin's starting base is templates/fxtime/pastBase.yaml: sandstoneBase's bounds with no cells
and no buildings. It reserves the same area, so every later template lands where it does on home,
but it does not carve the room or place a second printing pod. The past has no base.
"""
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = Path(sys.argv[1] if len(sys.argv) > 1 else
           os.path.join(os.environ.get("ONI_GAME", "."), "OxygenNotIncluded_Data/StreamingAssets/dlc/expansion1/"
                        "worldgen/worlds/VanillaSandstoneDefault.yaml"))


def drop_block(lines, start_pred, indent):
    """Remove each block whose first line passes start_pred, up to the next line at <= indent."""
    out, skipping = [], False
    for ln in lines:
        lead = len(ln) - len(ln.lstrip())
        if skipping:
            if ln.strip() and lead <= indent:
                skipping = False
            else:
                continue
        if start_pred(ln):
            skipping = True
            continue
        out.append(ln)
    return out


def drop_warp_rule(lines):
    """Remove the worldTemplateRules item that lists expansion1::poi/warp/sender."""
    items, cur, out = [], None, []
    for ln in lines:
        if ln.startswith("  - names:"):
            if cur is not None:
                items.append(cur)
            cur = [ln]
        elif cur is not None and (ln.startswith("    ") or not ln.strip()):
            cur.append(ln)
        else:
            if cur is not None:
                items.append(cur)
                cur = None
            items.append([ln])
    if cur is not None:
        items.append(cur)
    dropped = 0
    for it in items:
        if any("poi/warp/sender" in x for x in it):
            dropped += 1
            continue
        out.extend(it)
    if dropped != 1:
        sys.exit(f"expected exactly one warp sender rule, found {dropped}")
    return out


def main() -> int:
    lines = SRC.read_text().splitlines()
    lines = drop_block(lines, lambda l: l.startswith("subworldMixingRules:"), 0)
    lines = [l for l in lines if not re.match(r"^\s+- \(Mixing\d\)\s*$", l)]
    lines = drop_warp_rule(lines)
    body = "\n".join(lines) + "\n"
    for needle in ("Mixing", "poi/warp/"):
        if needle in body:
            sys.exit(f"{needle} still in the output")
    head = ("# GENERATED by make-twin.py from Klei's expansion1::worlds/VanillaSandstoneDefault.\n"
            "# Edit the script, not this file: home and twin must stay the same apart from the header lines.\n")
    out = HERE / "worlds"
    out.mkdir(exist_ok=True)
    home = body.replace("STRINGS.WORLDS.VANILLASANDSTONEDEFAULT.", "STRINGS.WORLDS.FXTIMETERRA.")
    twin = (body.replace("STRINGS.WORLDS.VANILLASANDSTONEDEFAULT.", "STRINGS.WORLDS.FXTIMETWINTERRA.")
            .replace("asteroidIcon: asteroid_vanilla_sandstone_start_kanim", "asteroidIcon: prehistoric_asteroid_so_kanim")
            .replace("startingBaseTemplate: bases/sandstoneBase", "startingBaseTemplate: fxtime/pastBase"))
    for a, b in ((home, body), (twin, body)):
        if a == b:
            sys.exit("a header substitution did not apply")
    if twin.count("fxtime/pastBase") != 1 or twin.count("prehistoric_asteroid_so_kanim") != 1:
        sys.exit("the twin's base or icon substitution did not apply exactly once")
    (out / "FxTimeTerra.yaml").write_text(head + home)
    (out / "FxTimeTwinTerra.yaml").write_text(head + twin)
    print(f"wrote {out}/FxTimeTerra.yaml and FxTimeTwinTerra.yaml ({len(lines)} lines each)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
